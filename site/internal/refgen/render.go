// Pages are the generated reference pages, relative to the site.
var Pages = []string{"app/docs/reference/errors/page.mdx", "app/docs/reference/config/page.mdx"}

// Defaults are the config sections whose struct has a Default method,
// built so their default values can be read.
var Defaults = map[string]func() any{
	"http":   func() any { c := new(server.Config); c.Default(); return c },
	"pg":     func() any { c := new(pg.Config); c.Default(); return c },
	"client": func() any { c := new(client.Config); c.Default(); return c },
}

// migrateDefaults returns the defaults of the migrate section, which has
// no Default method. Most of its keys override the environment profile's
// policy, from ProductionPolicy and DevelopmentPolicy; recheck and
// apply_timeout default to constants of the core module.
func (s *source) migrateDefaults() (map[string]string, error) {
	prod, dev := migrate.ProductionPolicy(), migrate.DevelopmentPolicy()
	for _, p := range []migrate.Policy{prod, dev} {
		if p.Approved != nil || p.LockWait != 0 || p.Debug {
			return nil, fmt.Errorf("refgen: a profile's policy sets Approved, LockWait or Debug, which migrateDefaults doesn't show: add them")
		}
	}
	profile := func(p, d any) string {
		if p == d {
			return code(p)
		}
		return code(p) + " in production, " + code(d) + " otherwise"
	}
	out := map[string]string{
		"mode":           profile(prod.Mode, dev.Mode),
		"max_risk":       profile(prod.MaxRisk, dev.MaxRisk),
		"allow_unknown":  profile(prod.AllowUnknown, dev.AllowUnknown),
		"tolerate_ahead": profile(prod.TolerateAhead, dev.TolerateAhead),
	}
	ttl := func(p migrate.Policy) string {
		if p.LockTTL == 0 {
			return duration(migrate.DefaultLockTTL) // as the Runner reads 0
		}
		return duration(p.LockTTL)
	}
	out["lock_ttl"] = profile(ttl(prod), ttl(dev))
	for key, name := range map[string]string{"recheck": "defaultRecheck", "apply_timeout": "defaultApplyTimeout"} {
		d, err := s.durationConst(Module, name)
		if err != nil {
			return nil, err
		}
		out[key] = code(duration(time.Duration(d)))
	}
	return out, nil
}

// Generate returns the reference pages for the core module, read from
// root, a directory in its workspace, keyed as in Pages.
func Generate(root string) (map[string]string, error) {
	s, err := load(root)
	if err != nil {
		return nil, err
	}
	return s.generate()
}

func (s *source) generate() (map[string]string, error) {
	kinds, err := s.kinds()
	if err != nil {
		return nil, err
	}
	codes, err := s.codes()
	if err != nil {
		return nil, err
	}
	statuses, err := s.statuses()
	if err != nil {
		return nil, err
	}
	sections, err := s.sections()
	if err != nil {
		return nil, err
	}
	mig, err := s.migrateDefaults()
	if err != nil {
		return nil, err
	}
	errPage, err := renderErrors(kinds, codes, statuses)
	if err != nil {
		return nil, err
	}
	cfgPage, err := renderConfig(sections, mig)
	if err != nil {
		return nil, err
	}
	return map[string]string{Pages[0]: errPage, Pages[1]: cfgPage}, nil
}

// Write regenerates the pages under site.
func Write(root, site string) error {
	pages, err := Generate(root)
	if err != nil {
		return err
	}
	for rel, body := range pages {
		p := filepath.Join(site, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			return err
		}
	}
	return nil
}

const generated = "{/* Generated by `go generate ./...` in site/ from Galleon's source. Don't edit it by hand. */}\n\n"

func renderErrors(kinds []string, codes []Code, statuses map[string]int) (string, error) {
	var b strings.Builder
	b.WriteString("---\ntitle: \"Errors\"\ndescription: \"Every error kind, and every error code Galleon's core module returns.\"\norder: 1\n---\n\n")
	b.WriteString(generated)
	b.WriteString("# Errors\n\n")
	b.WriteString("Every error Galleon returns has a kind and a stable code. See [Errors](/docs/concepts/errors) for how they work.\n\n")
	b.WriteString("## Kinds\n\n")
	b.WriteString("The problem+json `type` of an HTTP error is `urn:galleon:problem:` followed by its kind's name.\n\n")
	b.WriteString("| Kind | Name | HTTP | gRPC code |\n|---|---|---|---|\n")
	for i, name := range kinds {
		k := errs.Kind(i)
		if want := snakeCase(name); k.String() != want {
			return "", fmt.Errorf("refgen: errs.%s is Kind %d, which is named %s, not %s", name, i, k, want)
		}
		fmt.Fprintf(&b, "| `%s` | `%s` | %d | %d |\n", name, k.String(), k.HTTPStatus(), k.GRPCCode())
	}
	var client, internal []Code
	for _, c := range codes {
		// galleon.internal is the code clients get for all the others.
		if len(c.Kinds) == 1 && c.Kinds[0] == "Internal" && c.Code != "galleon.internal" {
			internal = append(internal, c)
		} else {
			client = append(client, c)
		}
	}
	for code := range meanings {
		if !slices.ContainsFunc(codes, func(c Code) bool { return c.Code == code }) {
			return "", fmt.Errorf("refgen: meanings lists %s, which the module doesn't return", code)
		}
	}
	for _, c := range codes {
		if meaning(c) == "" {
			return "", fmt.Errorf("refgen: %s has no doc comment and no message: describe it in meanings", c.Code)
		}
	}
	b.WriteString("\n## Codes\n\n")
	b.WriteString("A code is `<module>.<name>`. Codes are stable, so clients may switch on them. ")
	b.WriteString("These are the codes of Galleon's core module. Adapters, such as `adapters/dpg`, have their own.\n\n")
	b.WriteString("A code comes with the kind shown, and a few with more than one. The HTTP status is its kind's, except where the table gives the one its HTTP routes send; gRPC always uses the kind's code. ")
	b.WriteString("The messages are those it is returned with, where … stands for a value filled in.\n\n")
	b.WriteString("| Code | Kind | HTTP | Package | Meaning |\n|---|---|---|---|---|\n")
	for _, c := range client {
		status := ""
		if st, ok := statuses[c.Code]; ok {
			status = fmt.Sprint(st)
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s |\n", c.Code, kindList(c.Kinds), status, pkgList(c.Packages), cell(meaning(c)))
	}
	b.WriteString("\n## Internal codes\n\n")
	b.WriteString("These codes come with the `Internal` kind. They are logged and seen by Go callers, but clients never see them: ")
	b.WriteString("an HTTP or gRPC response carries `galleon.internal` and the message \"internal error\" instead.\n\n")
	b.WriteString("| Code | Package | Meaning |\n|---|---|---|\n")
	for _, c := range internal {
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", c.Code, pkgList(c.Packages), cell(meaning(c)))
	}
	return b.String(), nil
}

func kindList(list []string) string {
	var out []string
	for _, s := range list {
		out = append(out, "`"+s+"`")
	}
	return strings.Join(out, ", ")
}

func pkgList(list []string) string {
	var out []string
	for _, p := range list {
		out = append(out, "`"+pkgName(p)+"`")
	}
	return strings.Join(out, ", ")
}

func renderConfig(sections []Section, mig map[string]string) (string, error) {
	var b strings.Builder
	b.WriteString("---\ntitle: \"Configuration\"\ndescription: \"Every config section and key Galleon's own modules read.\"\norder: 2\n---\n\n")
	b.WriteString(generated)
	b.WriteString("# Configuration\n\n")
	b.WriteString("Each section is a key of the JSON config file. See [Modules and wiring](/docs/concepts/modules#configuration) for how config is loaded.\n\n")
	b.WriteString("A key marked **env** can also be set with the environment variable `<APP>_<SECTION>_<KEY>`, in upper case. The environment wins over the file. ")
	b.WriteString("A key marked **secret** is redacted in `App.ConfigReport()`.\n\n")
	b.WriteString("A `time.Duration` key is a number of nanoseconds in the file, as `encoding/json` reads it, and a string with a unit, such as `30s`, in the environment. ")
	b.WriteString("The `migrate` section's durations are strings with a unit in both. Defaults are shown with a unit. A blank default is the type's zero value: empty, `false` or `0`.\n")
	for _, s := range sections {
		var dv reflect.Value
		if def := Defaults[s.Name]; def != nil {
			dv = reflect.ValueOf(def()).Elem()
		} else if s.Name != "migrate" {
			return "", fmt.Errorf("refgen: section %q has no entry in Defaults", s.Name)
		}
		fmt.Fprintf(&b, "\n## %s\n\n", s.Name)
		fmt.Fprintf(&b, "Read by package `%s`.", pkgName(s.Package))
		if s.Name == "migrate" {
			b.WriteString(" Its keys, other than `recheck` and `apply_timeout`, override the app's migration policy. ")
			b.WriteString("A key left unset keeps the policy's value, which is the environment profile's unless the app changes it (see [Migrations](/docs/concepts/migrations#the-deploy-policy)).")
		}
		b.WriteString("\n\n| Key | Type | Default | Description |\n|---|---|---|---|\n")
		for _, f := range s.Fields {
			var marks []string
			if f.Env {
				marks = append(marks, "**env**")
			}
			if f.Secret {
				marks = append(marks, "**secret**")
			}
			key := "`" + f.Key + "`"
			if len(marks) > 0 {
				key += " " + strings.Join(marks, " ")
			}
			def, ok := defaultOf(dv, f.index)
			if !ok {
				return "", fmt.Errorf("refgen: %s.%s has a default the page can't show; teach defaultOf to write it", s.Name, f.Key)
			}
			if s.Name == "migrate" {
				def = mig[f.Key]
			}
			fmt.Fprintf(&b, "| %s | `%s` | %s | %s |\n", key, f.Type, def, cell(oneLine(f.Doc)))
		}
	}
	return b.String(), nil
}

// defaultOf returns the default of the field at index in v, a defaulted
// config struct, or "" for a zero value, a field in a map or slice, or no
// struct. It reports false for a default it can't write, such as a
// non-empty slice, since a blank would claim it is empty.
func defaultOf(v reflect.Value, index []int) (string, bool) {
	if !v.IsValid() || len(index) == 0 {
		return "", true
	}
	f, err := v.FieldByIndexErr(index)
	if err != nil || f.IsZero() {
		return "", true // under a nil pointer, or unset
	}
	if d, ok := f.Interface().(time.Duration); ok {
		return code(duration(d)), true
	}
	switch f.Kind() {
	case reflect.String, reflect.Bool, reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Float32, reflect.Float64:
		return code(f.Interface()), true
	}
	return "", false
}

func code(v any) string { return "`" + fmt.Sprint(v) + "`" }

// duration writes d without zero units: 1m, not 1m0s.
func duration(d time.Duration) string {
	s := d.String()
	if strings.HasSuffix(s, "m0s") {
		s = strings.TrimSuffix(s, "0s")
	}
	if strings.HasSuffix(s, "h0m") {
		s = strings.TrimSuffix(s, "0m")
	}
	return s
}

// meanings describe the codes that have neither a constant with a doc
// comment nor a message, since they wrap an error whose own message says
// what failed.
var meanings = map[string]string{
	"galleon.bad_request":      "The client couldn't build the HTTP request for an upstream call.",
	"galleon.encode_failed":    "A body couldn't be encoded: the client's request to an upstream, or the server's response.",
	"galleon.no_decoder":       "An operation was invoked with neither an input nor a way to decode one.",
	"galleon.panic":            "A handler panicked. The server recovered and logged it.",
	"galleon.upstream_timeout": "An upstream call outlasted the caller's deadline.",
}

var (
	kindPrefix = regexp.MustCompile(`^([A-Z][A-Za-z]*)(, (retryable))?: `)
	sqlstate   = regexp.MustCompile(`^[0-9A-Z]{5}$`)
)

// meaning describes a code: its constant's doc comment, without the kind
// it starts with (the Kind column shows it), whether it is retryable, and
// the comment on its line, such as its SQLSTATE; then the messages it is
// returned with.
func meaning(c Code) string {
	doc := oneLine(c.Doc)
	retryable := false
	if m := kindPrefix.FindStringSubmatch(doc); m != nil && slices.Contains(c.Kinds, m[1]) {
		doc = doc[len(m[0]):]
		retryable = m[3] != ""
	}
	note := oneLine(c.Note)
	if sqlstate.MatchString(note) {
		note = "SQLSTATE " + note
	}
	var parts []string
	if doc != "" {
		parts = append(parts, sentence(doc))
	}
	if retryable {
		parts = append(parts, "Retryable.")
	}
	if note != "" {
		parts = append(parts, sentence(note))
	}
	var msgs []string
	for _, m := range c.Messages {
		msgs = append(msgs, "“"+oneLine(m)+"”")
	}
	if m := meanings[c.Code]; len(parts) == 0 && m != "" {
		parts = append(parts, m)
	}
	if len(msgs) > 0 {
		parts = append(parts, "Message: "+strings.Join(msgs, "; ")+".")
	}
	return strings.Join(parts, " ")
}

// sentence capitalizes s and ends it with a period, but leaves a first
// word that is an identifier, such as statement_timeout or pg.Config, as it
// is.
func sentence(s string) string {
	s = strings.TrimSpace(s)
	if s == "" {
		return s
	}
	first, _, _ := strings.Cut(s, " ")
	if !identifier(first) {
		r, n := utf8.DecodeRuneInString(s)
		s = string(unicode.ToUpper(r)) + s[n:]
	}
	if !strings.HasSuffix(s, ".") && !strings.HasSuffix(s, "…") {
		s += "."
	}
	return s
}

// identifier reports whether a word is a name from code: it has an
// underscore, a dot or brackets inside it, or a capital after its start.
func identifier(w string) bool {
	w = strings.TrimRight(w, ",.:;")
	if strings.ContainsAny(w, "_.()[]`") {
		return true
	}
	for i, r := range w {
		if i > 0 && unicode.IsUpper(r) {
			return true
		}
	}
	return false
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

// cell makes text safe in an MDX table cell. Outside code spans, it escapes
// what MDX or Markdown would read as syntax; inside them, only the pipe,
// which would end the cell.
func cell(s string) string {
	prose := strings.NewReplacer("\\", "\\\\", "|", "\\|", "{", "\\{", "}", "\\}", "<", "&lt;", ">", "&gt;", "[", "\\[", "*", "\\*", "_", "\\_")
	parts := strings.Split(s, "`")
	for i, p := range parts {
		if i%2 == 0 || i == len(parts)-1 {
			parts[i] = prose.Replace(p) // prose, or an unclosed backtick's tail
		} else {
			parts[i] = strings.ReplaceAll(p, "|", "\\|")
		}
	}
	return strings.Join(parts, "`")
}

func pkgName(path string) string {
	if path == "" {
		return "galleon"
	}
	return path
}

func snakeCase(s string) string {
	var b strings.Builder
	for i, r := range s {
		if r >= 'A' && r <= 'Z' {
			if i > 0 {
				b.WriteByte('_')
			}
			r += 'a' - 'A'
		}
		b.WriteRune(r)
	}
	return b.String()
}
